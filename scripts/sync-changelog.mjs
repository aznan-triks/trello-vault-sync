import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const changelogPath = join(process.cwd(), "CHANGELOG.md");
const targetPath = join(process.cwd(), "src", "core", "bundledChangelog.ts");

const content = readFileSync(changelogPath, "utf8");

// Escapes non-ASCII characters to \uXXXX to satisfy CONTEXT.md §8/§9
// (zero literal accented characters in src/).
const asciiSafeJson = JSON.stringify(content).replace(/[\u007f-\uffff]/g, (c) => {
	return "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0");
});

const code = `// Auto-generated by scripts/sync-changelog.mjs — do not edit directly.
export const BUNDLED_CHANGELOG: string = ${asciiSafeJson};
`;

writeFileSync(targetPath, code, "utf8");
console.log("sync-changelog: bundledChangelog.ts updated from CHANGELOG.md (ASCII-safe).");
